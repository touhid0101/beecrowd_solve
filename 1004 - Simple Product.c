// 1004 - Simple Product - Beecrowd
#include <stdio.h>

int main() {
    // taking 2 numbers as input
    int num1, num2;
    scanf("%d", &num1);
    scanf("%d", &num2);

    // calculating the product
    int product = num1 * num2;

    // printing the output
    printf("PROD = %d\n", product);

    return 0;
}